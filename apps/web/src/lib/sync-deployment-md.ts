// Auto-write DEPLOYMENT.md to a repo after every successful deploy.
//
// The file gives coding agents (and humans) a canonical, current view of:
// where this app runs, how to deploy, what the live hostnames are, and what
// not to do on the server. Without it, every fresh session re-discovers the
// same facts from a stale local checkout and gets things wrong.

import { adminTokenCandidates } from './admin-ids'
import { account, and, db, eq, inArray } from './db'
import { commitFile, getRepoFile, parseGithubRepoUrl } from './github'
import {
	getContainerHostNetInfo,
	getNginxRoutes,
	inspectContainer,
} from './ssh'

import type { AppRepo } from './db'
import { managedContainerNames } from './managed-containers'
import { getServer, type ServerConfig } from './servers'
import { readOAuthAccessToken } from './oauth-token'
import { dashboardUrl } from './hosts'
import { SITE_URL } from './site'

interface DeploymentSnapshot {
	serverId: string
	containerName: string
	workingDir: string
	envFile: string | null
	hostnames: string[]
	branch: string
}

async function gatherSnapshot(
	server: ServerConfig,
	repo: AppRepo,
): Promise<DeploymentSnapshot | null> {
	let workingDir: string | null = null
	let envFile: string | null = null
	try {
		const detail = await inspectContainer(server, repo.containerName)
		workingDir = detail.compose.workingDir
		const envCandidate = `/opt/apps/${repo.containerName}.env`
		const mountedEnvs = detail.mounts.find((m) => m.destination?.endsWith('.env'))
		envFile = mountedEnvs?.source ?? envCandidate
	} catch {
		// no compose labels — skip; this isn't a powder-deployed app shape
	}
	if (!workingDir) return null

	const [nginxRoutes, netInfo, detail2] = await Promise.all([
		managedContainerNames(server.id).then((names) => getNginxRoutes(server, names)),
		getContainerHostNetInfo(server, [repo.containerName]),
		inspectContainer(server, repo.containerName),
	])
	const info = netInfo.get(repo.containerName)
	const hostPorts = new Set<number>()
	for (const portStr of detail2.ports) {
		// format: "127.0.0.1:3016 → 3000/tcp"
		const m = portStr.match(/:(\d+)\s*→/)
		if (m) {
			const n = Number(m[1])
			if (!Number.isNaN(n)) hostPorts.add(n)
		}
	}
	if (info?.networkMode === 'host' && info.envPort) hostPorts.add(info.envPort)

	const hosts = new Set<string>()
	for (const route of nginxRoutes) {
		if (!route.host) continue
		const isLocalhost = route.host === '127.0.0.1' || route.host === 'localhost'
		const portMatchesContainer = route.port != null && hostPorts.has(route.port)
		const dnsMatchesContainer = route.host === repo.containerName || route.host === info?.composeService
		if ((isLocalhost && portMatchesContainer) || dnsMatchesContainer) {
			for (const u of route.urls) {
				try {
					hosts.add(new URL(u).host)
				} catch {
					// ignore
				}
			}
		}
	}
	for (const t of info?.traefikHosts ?? []) hosts.add(t)

	return {
		serverId: server.id,
		containerName: repo.containerName,
		workingDir,
		envFile,
		hostnames: [...hosts].sort(),
		branch: repo.branch,
	}
}

export function renderMarkdown(snap: DeploymentSnapshot): string {
	const hostsLine = snap.hostnames.length
		? snap.hostnames.join(', ')
		: '_(none discovered — check nginx or Traefik labels)_'
	return `# Deployment

**This file is auto-generated by powder on every deploy.** Don't edit by hand — your changes will be overwritten the next time this app is deployed.

## Where this app runs

- **Server:** \`${snap.serverId}\`
- **Container:** \`${snap.containerName}\`
- **Source on server:** \`${snap.workingDir}\`
- **Env file:** \`${snap.envFile ?? '(none)'}\`
- **Hostnames:** ${hostsLine}

## How to deploy

\`\`\`
git push origin ${snap.branch}
\`\`\`

Powder webhook fires → ssh into \`${snap.serverId}\` → fresh clone into \`src/\` (fetch + hard-reset) → \`docker compose build ${snap.containerName}\` → \`docker compose up -d --force-recreate ${snap.containerName}\` (opt-in: with the label \`powder.bridge.enabled=true\` a temporary \`-powder-bridge\` clone of the running container serves traffic during the swap, so there is no 404 gap; opt-in release phase: the label \`powder.release.cmd=<shell cmd>\` runs that command once from the new image before the swap, and a failure keeps the old container serving). Watch progress at ${dashboardUrl()}/projects.

## What NOT to do

- **Don't edit files on the server** — powder hard-resets \`src/\` on every deploy, so local edits are silently lost.
- **Don't run \`git clean -fd\` on the server** — deletes \`.deploy-key\` and locks powder out.
- **Don't recreate the container manually from a different directory** — powder uses container labels to find the compose project; orphaning them breaks future webhook deploys.
- **Wildcard subdomains (\`*.foo.com\`)?** Add to nginx \`server_name\` AND configure DNS. The container doesn't auto-handle wildcards.

## When things break

- Live SSE log: ${dashboardUrl()}/projects → click this app
- Container logs: on server \`${snap.serverId}\`, run \`docker logs ${snap.containerName} --tail 100 -f\` (or use powder's container page)
- Prefer redeploying through powder (a hand build leaves no \`:deploy-<id>\` rollback tag and skips powder's build lock). Emergency manual rebuild: on server \`${snap.serverId}\`, run \`cd ${snap.workingDir} && docker compose build ${snap.containerName} && docker compose up -d --force-recreate ${snap.containerName}\` (before up: if the image has label powder.release.cmd, run \`docker compose run --rm --no-deps -T --entrypoint sh <svc> -c "<cmd>"\`, or redeploy through powder)
- Deploy docs: ${SITE_URL}/docs/deploys
`
}

function parseRepoUrl(repoUrl: string): { owner: string; name: string } | null {
	const r = parseGithubRepoUrl(repoUrl)
	return r ? { owner: r.owner, name: r.repo } : null
}

// only CURRENT admins' tokens (the owner first when an admin);
// there is no fallback to any GitHub account with repo scope, so a removed
// user's token never commits into an app's repo.
export async function pickGithubToken(ownerUserId: string | null): Promise<string | null> {
	const candidates = adminTokenCandidates(ownerUserId)
	if (candidates.length === 0) return null
	const rows = await db
		.select()
		.from(account)
		.where(and(eq(account.providerId, 'github'), inArray(account.userId, candidates)))
	const byUser = new Map(rows.map((r) => [r.userId, r]))
	for (const id of candidates) {
		const a = byUser.get(id)
		if (a?.accessToken && a.scope?.includes('repo')) return readOAuthAccessToken(a.accessToken)
	}
	return null
}

export async function syncDeploymentMd(
	repo: AppRepo,
	_gitSha: string | null,
): Promise<{ ok: boolean; reason?: string }> {
	// Opt-in per app (app_repos.sync_deployment_md, 0051): every sync commit is
	// a push into the app's repo, so never write one unless the app asked.
	if (!repo.syncDeploymentMd) return { ok: true, reason: 'disabled for this app' }
	const server = await getServer(repo.serverId)
	if (!server) return { ok: false, reason: `server ${repo.serverId} not found` }

	const snap = await gatherSnapshot(server, repo)
	if (!snap) return { ok: false, reason: 'no compose labels — skipping' }

	const parsed = parseRepoUrl(repo.repoUrl)
	if (!parsed) return { ok: false, reason: `unparseable repo_url: ${repo.repoUrl}` }

	const token = await pickGithubToken(repo.ownerUserId)
	if (!token) return { ok: false, reason: 'no github token with repo scope available' }

	// Hostname discovery is racy right after a swap (the new container's port
	// / net info may not be visible yet), so a deploy can briefly see zero
	// hosts. Rendering "(none discovered)" then, and the real hosts on the next
	// run, produced an alternating diff — and every sync commit is itself a
	// webhook deploy that restarts the container (extra swaps per real
	// deploy). Hostnames are sticky: an empty discovery
	// never overwrites hosts already in the committed file.
	if (snap.hostnames.length === 0) {
		try {
			const existing = await getRepoFile(token, parsed.owner, parsed.name, 'DEPLOYMENT.md', repo.branch)
			const line = existing?.match(/^- \*\*Hostnames:\*\* (.+)$/m)?.[1]?.trim()
			if (line && !line.startsWith('_(none discovered')) {
				snap.hostnames = line
					.split(',')
					.map((h) => h.trim())
					.filter(Boolean)
					.sort()
			}
		} catch {
			// best effort — fall through with the empty discovery
		}
	}

	const content = renderMarkdown(snap)
	try {
		const res = await commitFile(
			token,
			parsed.owner,
			parsed.name,
			'DEPLOYMENT.md',
			content,
			'deploy: sync DEPLOYMENT.md (auto)',
			repo.branch,
			{ skipIfUnchanged: true },
		)
		return { ok: true, reason: res.skipped ? 'unchanged — no commit' : undefined }
	} catch (err) {
		return { ok: false, reason: err instanceof Error ? err.message : 'commit failed' }
	}
}
