// ONE compose authority.
//
// powder never edits the user's compose file. Everything powder wants in it
// (traefik labels, loopback bindings for published ports) lives in its own
// override file next to it, `<workdir>/docker-compose.powder.yml`, passed as the
// LAST `-f` everywhere (composeFileArgs). Compose merges maps per key (later file
// wins) and appends lists, so:
//   - labels: the override's keys win over the user's, the user's other labels
//     (powder.public-port, powder.bridge.enabled, their own traefik keys) survive;
//   - ports: replaced with the `!override` tag (compose >= 2.24).
// Opt-outs are read from the RESOLVED config (`docker compose config --format
// json`), never from the raw file. Pure functions only here; the I/O writer is
// compose-override-io.ts (kept apart so fragments.ts can import this module
// without pulling in ssh).

import { createHash } from 'node:crypto'
import { posix } from 'node:path'

export const OVERRIDE_FILE = 'docker-compose.powder.yml'

/** Powder's per-deploy temp overrides. The deploy script passes
 *  `$DFR_DIR/override.yml` (rewritten Dockerfiles) and `$DFR_DIR/labels.yml`
 *  (pull_policy pins) to `compose up`, so compose records them in the container's
 *  `com.docker.compose.project.config_files` label; the script's EXIT trap deletes
 *  them. A file list read back from that label must never contain them, or every
 *  later compose call of the app (deploy preflight, guard probe, rollback, domain
 *  apply) fails with "open /tmp/powder-dfr.XXXXXX/override.yml: no such file". The
 *  staged-image override (`/tmp/powder-stage.XXXXXX`, build only) is matched too. */
export function isPowderTempComposeFile(path: string): boolean {
	const p = path.trim()
	if (/^\/tmp\/powder-(dfr\.[A-Za-z0-9]+\/(override|labels)\.yml|stage[.-][A-Za-z0-9_.-]+)$/.test(p)) return true
	// The per-deploy set lives in <state dir>/<key>/dfr/ (it stays on disk,
	// so the label names existing files); the deploy script adds the current one itself.
	return p.startsWith(`${composeStateBase()}/`) && /\/dfr\/(override|labels)\.yml$/.test(p)
}

/** Where a deploy keeps its per-deploy override set (rewritten Dockerfiles,
 *  override.yml, labels.yml): next to powder's compose override, outside every app dir
 *  and build context, replaced as a whole on each deploy. */
export function deployOverrideDirFor(configFile: string, composeFiles?: string[]): string {
	return `${overrideDirFor(configFile, composeFiles)}/dfr`
}
const OVERRIDE_HEADER =
	'# generated by powder, do not edit. Rewritten on every deploy; put your own changes in your compose file.'

/** Label that keeps a service's published ports on all interfaces. */
const PUBLIC_PORT_LABEL = 'powder.public-port'

/** `!override` (replace instead of append) needs compose v2.24. */
const MIN_COMPOSE_VERSION: readonly [number, number] = [2, 24]

const SAFE_PATH = /^[A-Za-z0-9_./-]+$/

/** Where powder keeps state per app OUTSIDE any repo checkout. One key function for the
 *  env state dir (`/var/lib/powder/env/<key>`) and the compose override dir
 *  (`/var/lib/powder/compose/<key>`): sha256(path)[:12] plus the basename. */
export function stateKeyFor(path: string): string {
	const base = (path.split('/').pop() || 'x').replace(/[^A-Za-z0-9._-]/g, '_').slice(0, 60)
	return `${createHash('sha256').update(path).digest('hex').slice(0, 12)}-${base}`
}

/** Base dir of the generated overrides. NOT inside the workdir: in the workdir layout the
 *  workdir IS the git checkout, so a repo-tracked docker-compose.powder.yml would survive
 *  the reset and become the last -f (privileged, host bind mounts). The env var is a test seam. */
export function composeStateBase(): string {
	return (process.env.POWDER_COMPOSE_STATE_DIR ?? '/var/lib/powder/compose').replace(/\/+$/, '')
}

/** The compose project dir: the dir of the first user compose file. */
function projectDirFor(configFile: string, composeFiles?: string[]): string {
	const files = (composeFiles && composeFiles.length > 0 ? composeFiles : [configFile]).filter(
		(f) => posix.basename(f) !== OVERRIDE_FILE && !isPowderTempComposeFile(f),
	)
	return posix.dirname(files[0] ?? configFile)
}

/** Directory of the override: /var/lib/powder/compose/<key of the project dir>. */
export function overrideDirFor(configFile: string, composeFiles?: string[]): string {
	return `${composeStateBase()}/${stateKeyFor(projectDirFor(configFile, composeFiles))}`
}

/** ABSOLUTE path of the override (passed as the last -f). The override contains no relative
 *  paths, so keeping it outside the project dir does not change project-dir resolution. */
export function overridePathFor(configFile: string, composeFiles?: string[]): string {
	return `${overrideDirFor(configFile, composeFiles)}/${OVERRIDE_FILE}`
}

/** The override path inside the project dir, where powder never writes it. Removed when untracked. */
export function inProjectOverridePathFor(configFile: string, composeFiles?: string[]): string {
	return `${projectDirFor(configFile, composeFiles)}/${OVERRIDE_FILE}`
}

/** True for a path that is safe to splice into a shell word without quoting games. */
export function isSafeOverridePath(p: string): boolean {
	return SAFE_PATH.test(p)
}

/** `docker compose version --short` text -> may `!override` be used. */
export function composeVersionOk(text: string): boolean {
	const m = text.trim().replace(/^v/, '').match(/^(\d+)\.(\d+)/)
	if (!m) return false
	const major = Number(m[1])
	const minor = Number(m[2])
	return major > MIN_COMPOSE_VERSION[0] || (major === MIN_COMPOSE_VERSION[0] && minor >= MIN_COMPOSE_VERSION[1])
}

// ── ports ────────────────────────────────────────────────────────────────────

const PROXY_IMAGE_RE = /(^|\/)(nginx|caddy|traefik|haproxy)([\/:@-]|$)/i
const INFRA_IMAGE_RE =
	/(^|\/)(postgres|postgresql|pgvector|mysql|mariadb|redis|valkey|memcached|mongo|clickhouse|elasticsearch|rabbitmq|minio)([\/:@]|$)/i

export type ResolvedPort = {
	target?: number
	published?: string | number
	host_ip?: string
	protocol?: string
	mode?: string
	name?: string
	app_protocol?: string
}

type ResolvedService = {
	image?: string
	ports?: ResolvedPort[]
	labels?: Record<string, string> | string[]
}

function labelValue(labels: ResolvedService['labels'], key: string): string | undefined {
	if (!labels) return undefined
	if (Array.isArray(labels)) {
		for (const l of labels) if (l.startsWith(`${key}=`)) return l.slice(key.length + 1)
		return undefined
	}
	const v = labels[key]
	return v === undefined ? undefined : String(v)
}

export interface PortPlan {
	/** service -> the FULL replacement ports list (long syntax entries). */
	overrides: Record<string, ResolvedPort[]>
	/** Log lines for the deploy output: `[ports] ...` and `left public: ...`. */
	notes: string[]
}

const isPublicIp = (ip: string | undefined) => !ip || ip === '0.0.0.0'
const isV6 = (ip: string | undefined) => !!ip && ip.includes(':')

/** Which published ports to bind to 127.0.0.1. The app service always (unless it
 *  carries powder.public-port=true); infra siblings (image list only, unless
 *  they carry the label); proxies and everything else are left and reported. */
export function planPorts(config: unknown, service: string, opts: { allowOverride: boolean } = { allowOverride: true }): PortPlan {
	const services = (config as { services?: Record<string, ResolvedService> })?.services ?? {}
	const plan: PortPlan = { overrides: {}, notes: [] }
	let bound = 0
	for (const [name, svc] of Object.entries(services)) {
		const ports = Array.isArray(svc.ports) ? svc.ports : []
		const published = ports.filter((p) => p.published !== undefined && p.published !== '')
		if (published.length === 0) continue
		const optOut = labelValue(svc.labels, PUBLIC_PORT_LABEL) === 'true'
		const image = (svc.image ?? '').toLowerCase()
		const isApp = name === service
		const isInfra = !isApp && !PROXY_IMAGE_RE.test(image) && INFRA_IMAGE_RE.test(image)
		if (isApp && optOut) {
			plan.notes.push(`[ports] ${PUBLIC_PORT_LABEL}=true - published ports left as written`)
			continue
		}
		if (!isApp && !isInfra) {
			if (published.some((p) => isPublicIp(p.host_ip) || isV6(p.host_ip))) {
				plan.notes.push(`left public: ${name} service is not the app service (ports not rewritten)`)
			}
			continue
		}
		if (isInfra && optOut) {
			plan.notes.push(`left public: ${name} opted out (${PUBLIC_PORT_LABEL}=true)`)
			continue
		}
		let changed = false
		const next = ports.map((p) => {
			if (p.published === undefined || p.published === '') return p
			if (isV6(p.host_ip)) {
				plan.notes.push(`left public: ${name} IPv6 binding (not rewritten)`)
				return p
			}
			if (isPublicIp(p.host_ip)) {
				changed = true
				bound++
				return { ...p, host_ip: '127.0.0.1' }
			}
			return p
		})
		if (!changed) continue
		if (!opts.allowOverride) {
			plan.notes.push(`left public: ${name} compose older than ${MIN_COMPOSE_VERSION.join('.')} cannot override ports (upgrade docker compose)`)
			bound = Math.max(0, bound - next.filter((p, i) => p !== ports[i]).length)
			continue
		}
		plan.overrides[name] = next
	}
	if (bound > 0) plan.notes.push(`[ports] bound ${bound} published port(s) to 127.0.0.1 (label ${PUBLIC_PORT_LABEL}=true keeps them public)`)
	else if (plan.notes.length === 0) plan.notes.push('[ports] no public bindings')
	return plan
}

// ── rendering ────────────────────────────────────────────────────────────────

const q = (s: string | number) => JSON.stringify(String(s))

/** The `- key=value` lines of a renderLabelsBlock() block, without the list dash. */
export function labelLinesFromBlock(block: string): string[] {
	return block
		.split('\n')
		.map((l) => l.match(/^\s+-\s+(.*)$/)?.[1])
		.filter((l): l is string => !!l)
}

/** capabilities powder drops from every service it overrides. NET_RAW (in
 *  Docker's default set) lets a container forge ARP and raw IP packets, e.g. spoof
 *  Traefik <-> powder on the shared `web` bridge. compose merges cap_drop lists across
 *  files (union), so the app's own entries stay. A container that runs `ping` inside
 *  loses it; the change applies when a deploy recreates the container. */
export const OVERRIDE_CAP_DROP = ['NET_RAW'] as const

/** The override file for one app service's labels plus any ports replacements, and
 * `cap_drop: [NET_RAW]` for every service in `services` (the services of the
 *  resolved user config), and `pull_policy: never` for every service with a
 *  build section: every recreate (composeUpCommand: `up --no-build`, which drops the
 *  build section) and deploy reads this file, so compose never PULLS a build service's
 *  `image:` with root's registry logins (a private repo of another project). The deploy's
 *  label step pins the services it built back to `missing` in a later file.
 *  Services without a build keep compose's default (a missing public image is pulled).
 *  Returns null when there is nothing to override.
 *  Deterministic: same inputs, same bytes (no deploy ids, no timestamps), so an
 *  unchanged render is a no-op. */
export function renderOverride(input: {
	service: string
	labels: string[] | null
	ports: Record<string, ResolvedPort[]>
	services?: string[]
	/** the services with a build section: pinned `pull_policy: never`. */
	buildServices?: string[]
}): string | null {
	const names = new Set<string>(Object.keys(input.ports))
	if (input.labels && input.labels.length > 0) names.add(input.service)
	const capDrop = new Set(input.services ?? [])
	for (const n of capDrop) names.add(n)
	const pinNever = new Set(input.buildServices ?? [])
	for (const n of pinNever) names.add(n)
	if (names.size === 0) return null
	const out: string[] = [OVERRIDE_HEADER, 'services:']
	for (const name of [...names].sort()) {
		out.push(`  ${q(name)}:`)
		if (name === input.service && input.labels && input.labels.length > 0) {
			out.push('    labels:')
			// `$` is compose interpolation syntax: escape it so a rule value survives verbatim.
			for (const l of input.labels) out.push(`      - ${q(l.replace(/\$/g, '$$$$'))}`)
		}
		const ports = input.ports[name]
		if (ports) {
			out.push('    ports: !override')
			for (const p of ports) {
				out.push(`      - target: ${Number(p.target)}`)
				if (p.published !== undefined && p.published !== '') out.push(`        published: ${q(p.published)}`)
				if (p.host_ip) out.push(`        host_ip: ${q(p.host_ip)}`)
				out.push(`        protocol: ${q(p.protocol ?? 'tcp')}`)
				if (p.mode) out.push(`        mode: ${q(p.mode)}`)
				if (p.name) out.push(`        name: ${q(p.name)}`)
				if (p.app_protocol) out.push(`        app_protocol: ${q(p.app_protocol)}`)
			}
		}
		if (capDrop.has(name)) {
			out.push('    cap_drop:')
			for (const c of OVERRIDE_CAP_DROP) out.push(`      - ${q(c)}`)
		}
		if (pinNever.has(name)) out.push('    pull_policy: never')
	}
	return out.join('\n') + '\n'
}

/** The labels powder wrote for `service` into an existing override (own format), or null. */
export function parseOverrideLabels(text: string | null, service: string): string[] | null {
	if (!text) return null
	const lines = text.split('\n')
	const at = lines.indexOf(`  ${q(service)}:`)
	if (at < 0) return null
	const out: string[] = []
	let inLabels = false
	for (const l of lines.slice(at + 1)) {
		if (/^ {2}\S/.test(l)) break
		if (l === '    labels:') {
			inLabels = true
			continue
		}
		if (/^ {4}\S/.test(l)) inLabels = false
		const m = inLabels ? l.match(/^ {6}- (".*")$/) : null
		if (m) {
			try {
				out.push((JSON.parse(m[1] ?? '') as string).replace(/\$\$/g, '$'))
			} catch {
				return null
			}
		}
	}
	return out.length > 0 ? out : null
}
