// Failed deploy logs in the shapes real deploys print them: BuildKit `#N`
// prefixed build output, colour-coded test runner output, powder's own refusal
// lines. Written for the tests (app, file and host names are invented); each
// case states the one-line summary the failure summary must give.
//
// `was`: what an older summary reader did with this shape, kept so the
// fixture says which class of mistake it guards:
//   - 'vague': said only "failed during: <step>" although the log names the cause
//   - 'wrong': named a cause the log does not support
//   - 'right': already right, kept so the new reader does not lose it

export interface DeployFailureLogCase {
	name: string
	was: 'vague' | 'wrong' | 'right'
	log: string
	/** the exact summary */
	summary: string
	/** the part of the summary that names the cause: it must survive every cut (a
	 *  GitHub commit status description holds 140 characters) */
	cause: string
}

const E = String.fromCharCode(27)
/** an SGR colour escape, as test runners print them */
const c = (codes: string) => `${E}[${codes}m`

