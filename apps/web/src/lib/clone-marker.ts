// Proof that a directory is one powder made for one owner, so a later re-clone or
// cleanup may move or remove it. Nothing is ever moved or removed by name alone.
//
// Two markers, both holding `powder-clone-target v1 <owner>` (`app:<name>`,
// `preview:<preview row id>`, `src:<app dir name>`):
// - `<dir>/.git/powder-clone-target` in a finished clone, written right after
//   `git clone` (under `.git/`, which no sync cleans: workdir syncs run no
//   `git clean`, and the src/ sync's clean skips `.git`);
// - `<tmp>/.powder-clone-owner` in a temp clone dir, written into the empty temp dir
//   BEFORE git runs (git clones into `<tmp>/repo`), so even a run killed mid-clone
//   leaves a temp dir that names its owner.
// A missing, different, linked or unreadable marker means powder cannot prove the
// directory is its own, and it stays untouched.
//
// Why a marker and not "a checkout of the same repository holding only tracked,
// ignored or powder files": an app created later under the same name can be a
// checkout of the same repository, and its data dirs (pgdata, uploads) are neither
// tracked nor powder-generated by name. A preview row id cannot be carried by
// another directory by accident.
import { shq } from './shell'

const MARKER = '.git/powder-clone-target'
const TMP_MARKER = '.powder-clone-owner'
const PURPOSE_RE = /^(app|preview|src):[A-Za-z0-9_.-]+$/

/** An owner string: a kind and a plain id, at most MAX_PURPOSE characters, so the
 *  marker value stays inside the 200 bytes the marker checks read. */
export const MAX_PURPOSE = 160
export function clonePurposeOk(purpose: string): boolean {
	return purpose.length <= MAX_PURPOSE && PURPOSE_RE.test(purpose)
}

function value(purpose: string): string {
	if (!clonePurposeOk(purpose)) throw new Error('bad clone purpose')
	return `powder-clone-target v1 ${purpose}`
}

/** Shell (one command): write the finished-clone marker into the clone at `dir`. */
export function cloneMarkerWriteShell(dir: string, purpose: string): string {
	return `printf '%s\\n' ${shq(value(purpose))} > ${shq(`${dir}/${MARKER}`)}`
}

/** Shell (one command): write the temp-dir marker into the (empty) temp dir `tmp`. */
export function cloneTmpMarkerWriteShell(tmp: string, purpose: string): string {
	return `printf '%s\\n' ${shq(value(purpose))} > ${shq(`${tmp}/${TMP_MARKER}`)}`
}

/** Shell test (a `{ ...; }` group): `dir` is a real directory whose real `.git`
 *  directory holds a regular marker file with exactly this owner. */
export function cloneMarkerMatchShell(dir: string, purpose: string): string {
	const d = shq(dir)
	const g = shq(`${dir}/.git`)
	return `{ [ -d ${d} ] && [ ! -L ${d} ] && [ -d ${g} ] && [ ! -L ${g} ] && ${fileIs(shq(`${dir}/${MARKER}`), purpose)}; }`
}

/** The same test on a directory named by a shell variable (`v`, e.g. `__d`). */
export function cloneMarkerMatchVarShell(v: string, purpose: string): string {
	varOk(v)
	return `{ [ -d "$${v}" ] && [ ! -L "$${v}" ] && [ -d "$${v}/.git" ] && [ ! -L "$${v}/.git" ] && ${fileIs(`"$${v}/${MARKER}"`, purpose)}; }`
}

/** Shell test: the temp clone dir named by variable `v` is a real directory holding a
 *  regular temp marker with exactly this owner. */
export function cloneTmpMarkerMatchVarShell(v: string, purpose: string): string {
	varOk(v)
	return `{ [ -d "$${v}" ] && [ ! -L "$${v}" ] && ${fileIs(`"$${v}/${TMP_MARKER}"`, purpose)}; }`
}

function varOk(v: string) {
	if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(v)) throw new Error('bad shell variable name')
}

function fileIs(m: string, purpose: string): string {
	return `[ -f ${m} ] && [ ! -L ${m} ] && [ "$(head -c 200 ${m} 2>/dev/null)" = ${shq(value(purpose))} ]`
}

/** The temp marker's file name, for the scripts that remove it once the temp dir is
 *  empty again. */
export const CLONE_TMP_MARKER = TMP_MARKER

/** An owner as a file-name part (`preview:pv_1` -> `preview-pv_1`). */
export function clonePurposeSlug(purpose: string): string {
	return value(purpose).slice('powder-clone-target v1 '.length).replace(':', '-')
}

export const APPS_ROOT = '/opt/apps'

/** A clone target powder may create, move or remove: exactly one plain segment
 *  below `root` (`/opt/apps/<name>`), the segment not starting with a dot, so never
 *  the root itself, never a `..`, never a deeper or outside path. Pure. `root` is
 *  /opt/apps; only tests pass another value. */
export function cloneTargetOk(path: string, root: string = APPS_ROOT): boolean {
	return (
		/^\/[A-Za-z0-9_./-]*[A-Za-z0-9_-]$/.test(root) &&
		!root.split('/').includes('..') &&
		path.startsWith(`${root}/`) &&
		/^[A-Za-z0-9_][A-Za-z0-9_.-]*$/.test(path.slice(root.length + 1))
	)
}
